        {
            Name = "CharacterStoryFilm", ZIndex = -10,
            _characterId = character.CharacterId, _chapter = chapter,
            _storyName = character.CharacterId, _atlasPath = path,
            _shotImages = new() { [0] = path },
            _hud = hud, _world = world, _aftermath = aftermath,
            _lines = Script(job, chapter, aftermath), _completed = completed,
        });
    }


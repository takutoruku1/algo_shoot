        var job = game.SelectedJob;
        var character = Jobs.Get(job);
        int chapter = game.CharacterChapter(job);
        string path = $"res://char/bg2/story/cg_{character.CharacterId}_playable_{(aftermath ? "aftermath" : "memory")}_v1.png";
